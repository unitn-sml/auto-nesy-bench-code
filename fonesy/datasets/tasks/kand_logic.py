"""Kand-Logic (``kand-logic``, ``kand-logic-2``): pairs of Kandinsky-pattern images.

Generated by ``make kand-logic`` into::

    fonesy/data/kand-logic[-simple]/{train,val,test}/images/<id>_{A,B}.png
    fonesy/data/kand-logic[-simple]/{train,val,test}/labels.json
        {"<id>": {"image_a": ..., "image_b": ..., "concepts": [shape, color, ...]}}

with 3 (``kand-logic``) or 2 (``kand-logic-2``) primitives per image.
"""

from __future__ import annotations

import json
from pathlib import Path

import torch
from torch.utils.data import DataLoader, Dataset
from torchvision import transforms
from PIL import Image

from fonesy.datasets.tasks.base import Task

_MEAN = (0.5, 0.5, 0.5)
_STD = (0.5, 0.5, 0.5)
_FIGURE_WIDTH = 120  # rsbench-code's kandinksy_generator.py WIDTH constant


class _KandLogicSplit(Dataset):
    """Yields ``(paired_image, concepts)`` — image_A/image_B concatenated width-wise."""

    def __init__(self, split_dir: Path, transform) -> None:
        labels_path = split_dir / "labels.json"
        self._images_dir = split_dir / "images"
        self._entries: dict[str, dict] = json.loads(labels_path.read_text())
        self._ids = sorted(self._entries.keys())
        self._transform = transform

    def __len__(self) -> int:
        return len(self._ids)

    def __getitem__(self, idx: int):
        entry = self._entries[self._ids[idx]]
        image_a = Image.open(self._images_dir / entry["image_a"]).convert("RGB")
        image_b = Image.open(self._images_dir / entry["image_b"]).convert("RGB")
        image_a = self._transform(image_a)
        image_b = self._transform(image_b)
        paired = torch.cat([image_a, image_b], dim=2)  # (3, H, 2W)
        concepts = torch.tensor(entry["concepts"], dtype=torch.long)
        return paired, concepts


class _KandLogicTaskBase(Task):
    """Shared implementation for the two Kand-Logic variants (differ in dataset dir)."""

    n_classes: int = 3      # unused directly by SPL (no separate classifier head)
    in_channels: int = 3
    image_size: int = _FIGURE_WIDTH  # per sub-image; paired width is 2x

    _dataset_dirname: str = ""  # set by subclasses

    def __init__(self, root: str) -> None:
        dataset_root = Path(root) / self._dataset_dirname
        if not dataset_root.exists():
            raise FileNotFoundError(
                f"{self._dataset_dirname} data not found at '{dataset_root}'.\n"
                "Run 'make kand-logic'."
            )
        self._root = dataset_root
        self._transform = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(_MEAN, _STD),
        ])

    def _split_dataset(self, split: str) -> _KandLogicSplit:
        return _KandLogicSplit(self._root / split, self._transform)

    def train_loader(self, batch_size: int) -> DataLoader:
        return DataLoader(
            self._split_dataset("train"), batch_size=batch_size, shuffle=True,
            num_workers=2, pin_memory=torch.cuda.is_available(),
        )

    def val_loader(self, batch_size: int) -> DataLoader:
        return DataLoader(
            self._split_dataset("val"), batch_size=batch_size, shuffle=False,
            num_workers=2, pin_memory=torch.cuda.is_available(),
        )

    def test_loader(self, batch_size: int) -> DataLoader:
        return DataLoader(
            self._split_dataset("test"), batch_size=batch_size, shuffle=False,
            num_workers=2, pin_memory=torch.cuda.is_available(),
        )


class KandLogicTask(_KandLogicTaskBase):
    """Kand-Logic: 3-primitive paired Kandinsky-pattern images, 12 raw concept values."""

    _dataset_dirname = "kand-logic"


class KandLogicSimpleTask(_KandLogicTaskBase):
    """Kand-Logic-Simple: 2-primitive paired Kandinsky-pattern images, 8 raw concept values."""

    _dataset_dirname = "kand-logic-2"
